namespace MBI.Core
{
    /// <summary>
    /// **튜토리얼 첫 목표의 잣대** — 「그 칸이 채워졌는가」가 아니라
    /// **「물류 연결이 성립했는가」** (2026-10-02 · `260928_W01` 3장 사용자 확정의 이행).
    ///
    /// ⚠️⚠️ **왜 바꿨나 — 문서와 구현이 갈라져 있었고, 그 틈이 플레이어를 가뒀다.**
    /// 튜토리얼 기획서 4-1 의 종료 조건 앞쪽은 09-28 에 **「물류 연결이 성립했고」**로
    /// 확정됐는데, 코드는 `GhostCellFilled`, 곧 **「그 칸에 무엇이든 놓였는가」**만 봤다
    /// (내가 `260930_V01` 청 3 에 그렇게 보고해 놓고 이행하지 않았다).
    ///
    /// 그 틈의 대가를 10-02 에 실제로 재현했다 —
    /// 안내는 「벨트 — 빈 칸을 터치」인데 조립 모드의 탭은 **팔레트에 골라진 것**을 놓는다
    /// (기본값이 변환기 · `BoardController` 의 `Place` → `CurrentNode` · 이 분기는
    /// `8a62155`(09-15 제스처 개편)부터다). 그래서 변환기가 서면 —
    ///   · 칸은 채워졌으므로 **첫 목표가 켜진다**
    ///   · 그러나 벨트 줄은 끊긴 채라 그 변환기는 **가동률 0%**
    ///   · 생산 0 · 재고 0 이라 마운트가 안 차고 **둘째 목표가 영영 안 켜진다**
    /// 첫 걸음을 맞게 밟은 것처럼 보이는데 두 번째에서 막힌다.
    ///
    /// 📌 **그래서 묻는 것을 바꾼다** — 놓였는가가 아니라 **흐르는가**.
    ///
    /// ⚠️ **가정이다**(설계 역기입 자리). 「연결 성립」의 코드 뜻을 **군수 생산율이 0보다
    /// 큰가**로 잡았다. 고른 까닭 둘 —
    ///   ① <c>TutorialMountProbe</c> 가 재는 것과 **같은 잣대**다(그 프로브는 시작 보드로
    ///      25.4초 만충을 낸다 — 사슬이 멀쩡하다는 증거가 이 값에서 나온다).
    ///   ② **못 속인다.** 칸을 채우기만 해서는 0 이고, 줄이 이어져 물건이 흘러야 올라간다.
    ///
    /// ⚠️ **막·고스트·국면은 안 건드렸다.** 그쪽은 여전히 `GhostCellFilled`(물리적으로
    /// 채워졌는가)를 읽는다 — 채운 칸 위에 막이 남으면 그것대로 「고장」으로 읽힌다.
    /// 그래서 **보이는 것은 그대로 두고 세는 것만 엄격해진다.** 변환기를 놓은 플레이어는
    /// 막이 걷힌 뒤에도 첫 목표가 꺼져 있는 것을 보고, **끌어서 지우고** 벨트를 놓을 수 있다
    /// (제거는 튜토리얼에 잠겨 있지 않다 — `RemovalRules` 는 코어만 막는다).
    /// </summary>
    public static class TutorialLinkRule
    {
        /// <summary>
        /// **물류가 실제로 돌고 있는가.** 값은 `LogisticsOutputBridge.AmmoProduce`
        /// (라이브 네트워크 군수 생산율 · 발/초)를 그대로 받는다.
        ///
        /// ⚠️ **0 과 음수를 같이 거짓으로 둔다** — 음수는 나올 자리가 없지만, 나온다면
        /// 그것은 「돈다」가 아니다. 없는 값을 참으로 읽지 않는다.
        /// </summary>
        public static bool LinkIsLive(float ammoProducePerSecond) => ammoProducePerSecond > 0f;
    }
}
