namespace MBI.Core.Audio
{
    /// <summary>
    /// 소리 채널 셋 (사운드 문서 7장 「채널 분리」).
    ///
    /// **조작음을 효과음에서 갈라 둔 근거가 문서에 있다** — 조작음은 플레이어가 스스로 낸
    /// 소리이고 효과음은 게임이 내는 소리라, 한 채널에 두면 「내 손가락 소리만 줄이기」가 안 된다.
    /// 배경 음악을 또 가른 것은 **방치형에서 음악만 끄고 상태 알림은 남기고 싶은 사람**이 많아서다.
    /// </summary>
    public enum AudioChannel
    {
        /// <summary>배경 음악 — 흘려 재생. 화면이 바뀌어도 안 끊는다.</summary>
        Music = 0,
        /// <summary>효과음 — 게임이 내는 소리. 겹침 상한이 걸린다.</summary>
        Sfx = 1,
        /// <summary>조작음 — 플레이어가 낸 소리. 가장 작다.</summary>
        Ui = 2,
    }

    /// <summary>
    /// 볼륨의 **상대 순서**만 가르는 갈래 (사운드 문서 2장).
    ///
    /// ⚠️ **절대값은 문서가 정하지 않는다** — 기기와 재생 환경에 따라 달라져 박아 두면
    /// 곧 틀린 값이 된다. 문서가 붙드는 것은 **관계 하나**이고 그것이 이 열거의 순서다:
    /// <b>경고 &gt; 효과음 &gt; 조작음.</b>
    ///
    /// ⚠️ **채널과 다른 축이다.** 경고음은 효과음 채널로 나가되 **더 크게** 나간다 —
    /// 채널은 「무엇을 끌 수 있는가」를 가르고 이 갈래는 「무엇이 더 크게 들리는가」를 가른다.
    /// </summary>
    public enum SoundKind
    {
        /// <summary>경고 — 병목처럼 화면을 안 봐도 닿아야 하는 것. 가장 크다.</summary>
        Warning = 0,
        /// <summary>효과음 — 게임이 내는 나머지.</summary>
        Effect = 1,
        /// <summary>조작음 — 조립 화면의 딸깍. 가장 작다.</summary>
        Ui = 2,
    }

    /// <summary>
    /// 배경 음악의 국면 (사운드 문서 6장 「화면이 아니라 국면으로 나눈다」).
    ///
    /// ⚠️ **화면이 아니다.** 조립 화면으로 들어가도 곡이 안 바뀐다 — 그것이 바뀌는 것은
    /// 화면 전환이고, 여기서 가르는 것은 국면 전환이다.
    /// </summary>
    public enum MusicPhase
    {
        Battle = 0,
        Boss = 1,
    }
}
