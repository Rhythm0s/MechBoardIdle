namespace MBI.Core.Audio
{
    /// <summary>
    /// 배경 음악을 **언제 틀기 시작하는가** (2026-09-10 · 플랜 §67-3 결함 ③).
    ///
    /// **왜 규칙이 필요해졌는가.** 웹에서는 오디오가 **사용자가 무언가를 누르기 전까지 잠겨
    /// 있다.** 그래서 부팅하자마자 건 재생은 소리 없이 흘러가고, 나중에 볼륨을 올려도
    /// **이미 흘러가 버린 그 재생**은 살아나지 않는다 — 사용자가 본 「즉시 안 나고
    /// 스테이지를 옮기면 난다」가 그것이다(스테이지 이동이 새 재생을 걸어 준다).
    ///
    /// 그래서 **재생 시작을 사람이 누른 순간 안으로 옮긴다.** 누를 자리는 둘이다 —
    /// 「게임 시작」과 **볼륨 슬라이더**다. 슬라이더도 세는 이유는 메뉴에서 소리를
    /// 맞춰 보려는 사람에게 **미리듣기**가 있어야 하기 때문이다.
    ///
    /// ⚠️ **이 규칙은 「틀어도 되는가」만 답한다.** 무엇을 트는지(국면)와 얼마나 크게
    /// 트는지(볼륨)는 각각 다른 자리가 든다.
    /// </summary>
    public static class MusicStartRule
    {
        /// <summary>
        /// 지금 재생을 걸어도 되는가.
        ///
        /// 메뉴가 떠 있는 동안에는 **누른 적이 없으므로** 걸지 않는다.
        /// 다만 **볼륨을 만졌다면 그것이 누른 것**이라 미리듣기를 연다.
        /// </summary>
        public static bool ShouldStart(bool menuOpen, bool previewRequested) =>
            !menuOpen || previewRequested;
    }
}
