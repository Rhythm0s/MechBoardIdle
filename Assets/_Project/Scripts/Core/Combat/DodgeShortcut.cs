using UnityEngine;

namespace MBI.Core.Combat
{
    /// <summary>
    /// PC 회피 단축키가 **어느 쪽으로** 피할지 (2026-09-16 · `260915_W01` 판정 5).
    ///
    /// ⚠️⚠️ **왜 단축키가 필요했나.** 회피는 지금 **화면 플릭** 하나로만 들어온다.
    /// 그런데 플릭은 **촬영본에 입력이 안 남는다** — 화면에서는 로봇이 저 혼자 피한 것처럼
    /// 보이고, 「이 게임은 손으로 피할 수 있다」가 영상에서 증명되지 않는다.
    ///
    /// ⚠️ **플릭을 대신하지 않는다.** 둘은 나란히 산다 — 터치는 그대로 두고 키가 하나 는다.
    ///
    /// 📌 **방향을 여기서만 정한다.** 키를 읽는 곳과 방향을 정하는 곳을 갈라 두어야
    /// 시험이 값만 볼 수 있다(키보드 없이 못 도는 시험을 만들지 않는다).
    /// </summary>
    public static class DodgeShortcut
    {
        /// <summary>
        /// 어느 쪽으로 피하는가. 피할 근거가 없으면 <c>null</c> — **그때는 아무 일도 안 한다.**
        ///
        /// 차례는 둘이다.
        /// ① **가고 있던 쪽** — 손이 이미 방향을 말하고 있으면 그 말을 따른다.
        ///    누르던 방향과 다른 쪽으로 튀면 「내가 시킨 것」으로 안 읽힌다.
        /// ② **표적 반대쪽** — 손이 아무 말도 안 하면 맞고 있는 쪽에서 물러난다.
        ///    ⚠️ **가정이다**(문서에 회피 기본 방향 절이 없다 · 설계 역기입 자리).
        ///    근거는 「회피」라는 낱말이 가리키는 쪽이 그쪽 하나뿐이라는 것이다.
        ///
        /// ⚠️ 표적도 없고 가는 쪽도 없으면 **스택을 안 쓴다.** 아무 쪽으로나 굴리면
        /// 플레이어가 아껴 둔 스택이 뜻 없이 사라진다.
        /// </summary>
        /// <param name="move">지금 누르고 있는 이동 입력(정규화 전).</param>
        /// <param name="aim">사거리 안 표적까지의 방향. 표적이 없으면 <c>null</c>.</param>
        public static Vector2? Direction(Vector2 move, Vector2? aim)
        {
            if (move.sqrMagnitude > 1e-6f) return move.normalized;
            if (aim.HasValue && aim.Value.sqrMagnitude > 1e-6f) return (-aim.Value).normalized;
            return null;
        }
    }
}
